// the log return a sector should have made between two moments, from the real curves
export function macroReturn(sector, t0, t1) {
  const w = W[sector] || { mkt: 1 }; let r = 0;
  for (const k in w) r += w[k] * (lnCurve(k, t1) - lnCurve(k, t0));
  return r;
}
export const marketReturn = (t0, t1) => lnCurve('mkt', t1) - lnCurve('mkt', t0);
