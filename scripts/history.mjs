const C = {}; for (const k in A) C[k] = A[k].map(([d, v]) => [P(d), Math.log(v)]);
// natural log of a curve at time t (straight lines in log space between the known points)
export function lnCurve(name, t) {
  const c = C[name]; if (t <= c[0][0]) return c[0][1]; if (t >= c[c.length - 1][0]) return c[c.length - 1][1];
  let i = 1; while (c[i][0] < t) i++;
  const [t0, v0] = c[i - 1], [t1, v1] = c[i]; return v0 + (v1 - v0) * (t - t0) / (t1 - t0);
}
